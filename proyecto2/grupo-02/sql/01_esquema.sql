    CONSTRAINT pk_reclamo_garantia PRIMARY KEY (reclamo_id),
    CONSTRAINT uq_reclamo_orden_nueva UNIQUE (orden_nueva_id),
    CONSTRAINT fk_reclamo_garantia FOREIGN KEY (garantia_id) REFERENCES garantia (garantia_id),
